#!/usr/bin/env python3
"""DEV-TIME ONLY. Writes verifier/src/precog_verifier/bls/h2c_constants.py from the text of RFC 9380:
the SSWU curve constants A', B' (section 8.8.1) and the 11-isogeny coefficients k_(i,j) (appendix E.2).

The generated file is checked in and reviewed; the runtime never reads the RFC. Correctness of every constant
is established by the RFC 9380 J.9.1 vectors (tests/test_bls_hash_to_curve.py), not by this script.

Usage: python verifier/tools/gen_bls_constants.py --rfc PATH/TO/rfc9380.txt
"""
import argparse
import re
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "precog_verifier" / "bls" / "h2c_constants.py"


def clean(text: str) -> list[str]:
    out = []
    for line in text.replace("\r\n", "\n").split("\n"):
        line = line.replace("\x0c", "")
        if line.startswith("Faz, et al.") or line.startswith("RFC 9380 ") or line.startswith("Faz-Hernandez"):
            continue
        out.append(line)
    return out


def take(lines, start_idx, first_re):
    """Collect a hex constant that may wrap onto following indented lines."""
    m = re.search(first_re, lines[start_idx])
    val = m.group(1)
    j = start_idx + 1
    while j < len(lines) and lines[j].strip() and re.fullmatch(r"\s+[0-9a-f]+", lines[j]):
        val += lines[j].strip()
        j += 1
    return int(val, 16)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rfc", default=None)
    args = ap.parse_args()
    text = Path(args.rfc).read_text(encoding="utf-8") if args.rfc else urllib.request.urlopen("https://www.rfc-editor.org/rfc/rfc9380.txt", timeout=60).read().decode()
    lines = clean(text)
    s = next(i for i, l in enumerate(lines) if l.startswith("8.8.1.  BLS12-381 G1"))
    a = next(i for i in range(s, s + 60) if "A' = 0x" in lines[i])
    b = next(i for i in range(s, s + 60) if "B' = 0x" in lines[i])
    A = take(lines, a, r"A' = 0x([0-9a-f]+)")
    B = take(lines, b, r"B' = 0x([0-9a-f]+)")
    e2 = next(i for i, l in enumerate(lines) if l.startswith("E.2.  11-Isogeny Map for BLS12-381 G1"))
    e3 = next(i for i, l in enumerate(lines) if l.startswith("E.3.  3-Isogeny Map for BLS12-381 G2"))
    ks: dict[tuple[int, int], int] = {}
    for i in range(e2, e3):
        m = re.match(r"\s+\*  k_\((\d+),(\d+)\) = 0x([0-9a-f]+)$", lines[i])
        if m:
            val = m.group(3)
            j = i + 1
            while j < e3 and lines[j].strip() and re.fullmatch(r"\s+[0-9a-f]+", lines[j]):
                val += lines[j].strip()
                j += 1
            ks[(int(m.group(1)), int(m.group(2)))] = int(val, 16)
    sizes = {1: 12, 2: 10, 3: 16, 4: 15}  # x_num, x_den (monic: x^10 implicit), y_num, y_den (monic: x^15 implicit)
    for k, n in sizes.items():
        assert sorted(j for (i, j) in ks if i == k) == list(range(n)), (k, n)
    def poly(k):
        return "(\n" + "".join(f"    0x{ks[(k, j)]:x},\n" for j in range(sizes[k])) + ")"
    body = f'''"""Constants of the hash-to-curve suite BLS12381G1_XMD:SHA-256_SSWU_RO_ (RFC 9380 section 8.8.1, appendix E.2).

GENERATED by verifier/tools/gen_bls_constants.py from the RFC text; do not edit by hand. Each coefficient list is
ordered from the constant term upwards. The denominators are monic: their leading term (x^10 and x^15) is implicit.
"""

SSWU_A = 0x{A:x}
SSWU_B = 0x{B:x}
SSWU_Z = 11
H_EFF = 0xD201000000010001

ISO_X_NUM = {poly(1)}
ISO_X_DEN = {poly(2)}
ISO_Y_NUM = {poly(3)}
ISO_Y_DEN = {poly(4)}
'''
    OUT.write_bytes(body.encode("utf-8"))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
