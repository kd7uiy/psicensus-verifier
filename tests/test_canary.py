"""Verifiable canary guesses (SPEC amendment 9).

A row with source == "canary" must carry guesses == derive(m) for a whole minute m with
sealed_at_ms - 600000 <= m <= sealed_at_ms, and test_id "card5". Failing that is an ERROR
(canary.guesses_mismatch) from registration_ms on, and a WARNING (canary.unverified, with the count) before it.
The shared vectors are generated by the Worker's TypeScript; this file
checks them with an independent Python implementation.
"""
import hashlib
import json
from pathlib import Path

import pytest

from precog_verifier import canary, testing
from precog_verifier.release import verify_release

VECTORS = json.loads((Path(__file__).parent / "data" / "canary_v1" / "guesses.json").read_text())
MIN = 60_000


def codes(items):
    return [e.code for e in items]


def canary_row(data):
    return next(r for r in data.batches if r["source"] == "canary")


def player_row(data):
    return next(r for r in data.batches if r["source"] == "player" and r["sealed_at_ms"] >= data.manifest["registration_ms"])


# ------------------------------------------------------------- derivation
def test_tag_is_the_new_tag():
    assert canary.TAG == b"precog/canary/v1"
    assert VECTORS["tag"] == "precog/canary/v1"


@pytest.mark.parametrize("case", VECTORS["cases"], ids=lambda c: c["name"])
def test_shared_vectors(case):
    assert canary.derive_guesses(int(case["slot_ms"])) == case["guesses"]


def test_vectors_cover_zero_a_real_slot_and_u64_max():
    names = {c["name"] for c in VECTORS["cases"]}
    assert {"slot_zero", "slot_2026_real", "slot_u64_max_whole_minute"} <= names
    top = next(c for c in VECTORS["cases"] if c["name"] == "slot_u64_max_whole_minute")
    assert int(top["slot_ms"]) % MIN == 0 and int(top["slot_ms"]) + MIN > (1 << 64) - 1


def test_derivation_written_out_by_hand():
    slot = 1_791_852_060_000
    want = ""
    for i in range(25):
        h = hashlib.sha256(b"precog/canary/v1" + slot.to_bytes(8, "big") + i.to_bytes(4, "big")).digest()
        want += str(int.from_bytes(h[:8], "big") % 5)
    assert canary.derive_guesses(slot) == want


def test_canary_tag_differs_from_the_target_tag():
    from precog_verifier.targets import TAG as TARGET_TAG

    assert canary.TAG != TARGET_TAG


@pytest.mark.parametrize("bad", [-1, 1 << 64, 1.5, True, "5"])
def test_bad_slots_are_rejected(bad):
    with pytest.raises(ValueError):
        canary.derive_guesses(bad)


# ------------------------------------------------------------- the window rule
def test_window_has_at_most_eleven_candidates():
    assert len(canary.candidate_slots(10 * MIN)) == 11  # a whole minute: 0..10 minutes back inclusive
    assert len(canary.candidate_slots(20 * MIN)) == 11
    assert len(canary.candidate_slots(20 * MIN + 1)) == 10
    assert len(canary.candidate_slots(20 * MIN + 59_999)) == 10
    assert list(canary.candidate_slots(3 * MIN + 5)) == [0, MIN, 2 * MIN, 3 * MIN]  # never before time zero
    assert list(canary.candidate_slots(0)) == [0]
    assert all(m % MIN == 0 for m in canary.candidate_slots(1_791_852_060_123))


def test_window_edges_accept_and_reject():
    m = 1_791_852_060_000
    s = m + 17_000  # sealed 17 s after a whole minute
    ok = canary.derive_guesses
    assert canary.row_matches(ok(m), "card5", s)  # same minute
    assert canary.row_matches(ok(m - 9 * MIN), "card5", s)  # 9 minutes back
    assert not canary.row_matches(ok(m - 10 * MIN), "card5", s)  # 10 min 17 s back: outside
    assert not canary.row_matches(ok(m + MIN), "card5", s)  # a slot in the future
    assert not canary.row_matches(ok(m + 1), "card5", s)  # an unaligned value is never a slot
    assert canary.row_matches(ok(m), "card5", m)  # sealed exactly on a whole minute: both ends are included
    assert canary.row_matches(ok(m - 10 * MIN), "card5", m)
    assert not canary.row_matches(ok(m - 11 * MIN), "card5", m)
    assert not canary.row_matches(ok(m + MIN), "card5", m)


def test_test_id_must_be_card5():
    s = 1_791_852_060_000
    assert canary.row_matches(canary.derive_guesses(s), "card5", s)
    assert not canary.row_matches(canary.derive_guesses(s), "other", s)


def test_a_random_batch_matches_with_negligible_chance():
    for k in range(1000):
        g = "".join(str(b % 5) for b in hashlib.sha256(b"rand%d" % k).digest()[:25])
        assert not canary.row_matches(g, "card5", 1_791_852_060_000 + k * 1000)


# ------------------------------------------------------------- inside a release
def test_sample_canary_row_is_derived_and_the_release_is_clean(sample):
    res = verify_release(sample)
    assert res.ok and testing.real_warnings(res) == []
    r = canary_row(sample)
    assert canary.row_matches(r["guesses"], r["test_id"], r["sealed_at_ms"])


def test_relabelled_player_row_is_an_error_after_registration(sample):
    victim = player_row(sample)
    victim["source"] = "canary"  # the operator's relabelling: nothing hashed changes
    res = verify_release(sample)
    assert not res.ok
    errs = [e for e in res.errors if e.code == "canary.guesses_mismatch"]
    assert len(errs) == 1
    assert errs[0].batch_id == victim["batch_id"] and errs[0].anchor_seq == victim["anchor_seq"]
    assert "analysis.withheld" in codes(res.errors)
    assert res.analysis.S is None and res.analysis.z is None
    assert "canary.unverified" not in codes(res.warnings)


def test_relabelled_player_row_is_a_warning_before_registration(sample):
    sample.manifest["registration_ms"] = 10**15  # everything was sealed before registration (the beta)
    victims = [r for r in sample.batches if r["source"] == "player"][:3]
    for r in victims:
        r["source"] = "canary"
    res = verify_release(sample)
    assert res.ok, res.errors
    w = [x for x in res.warnings if x.code == "canary.unverified"]
    assert len(w) == 1 and "count=3" in w[0].detail
    assert "canary.guesses_mismatch" not in codes(res.errors)


def test_a_row_sealed_exactly_at_registration_is_an_error(sample):
    victim = player_row(sample)
    sample.manifest["registration_ms"] = victim["sealed_at_ms"]  # sealed_at_ms >= registration_ms includes equality
    victim["source"] = "canary"
    res = verify_release(sample)
    assert "canary.guesses_mismatch" in codes(res.errors) and "canary.unverified" not in codes(res.warnings)
    sample.manifest["registration_ms"] = victim["sealed_at_ms"] + 1  # one millisecond before registration: beta
    res = verify_release(sample)
    assert "canary.guesses_mismatch" not in codes(res.errors) and "canary.unverified" in codes(res.warnings)


def test_beta_and_registered_rows_split_by_sealed_time(sample):
    players = sorted((r for r in sample.batches if r["source"] == "player"), key=lambda r: r["sealed_at_ms"])
    early, late = players[0], players[-1]
    assert early["sealed_at_ms"] < sample.manifest["registration_ms"] <= late["sealed_at_ms"]
    early["source"] = late["source"] = "canary"
    res = verify_release(sample)
    assert codes(res.errors).count("canary.guesses_mismatch") == 1
    w = [x for x in res.warnings if x.code == "canary.unverified"]
    assert len(w) == 1 and "count=1" in w[0].detail


def test_good_canary_rows_in_the_beta_cause_no_warning(sample):
    sample.manifest["registration_ms"] = 10**15
    res = verify_release(sample)
    assert res.ok and "canary.unverified" not in codes(res.warnings)


def test_canary_sealed_9_minutes_after_its_slot_passes():
    res = verify_release(testing.build_sample_release(canary_lag_minutes=9))
    assert res.ok and testing.real_warnings(res) == []


def test_canary_sealed_11_minutes_after_its_slot_fails():
    data = testing.build_sample_release(canary_lag_minutes=11)
    assert "canary.guesses_mismatch" in codes(verify_release(data).errors)
    data.manifest["registration_ms"] = 10**15
    res = verify_release(data)
    assert res.ok and "canary.unverified" in codes(res.warnings)


def test_canary_with_another_test_id_fails_like_a_bad_guess():
    data = testing.build_sample_release(canary_test_id="other")
    assert "canary.guesses_mismatch" in codes(verify_release(data).errors)
    data.manifest["registration_ms"] = 10**15
    res = verify_release(data)
    assert res.ok and "canary.unverified" in codes(res.warnings)


def test_ordinary_player_rows_do_not_carry_the_canary_guesses(sample):
    r = player_row(sample)
    assert not canary.row_matches(r["guesses"], r["test_id"], r["sealed_at_ms"])
    assert verify_release(sample).ok


def test_one_error_per_bad_row(sample):
    for r in [x for x in sample.batches if x["source"] == "player" and x["sealed_at_ms"] >= sample.manifest["registration_ms"]][:4]:
        r["source"] = "canary"
    res = verify_release(sample)
    assert codes(res.errors).count("canary.guesses_mismatch") == 4
